# -- The command line ----------------------------------------------------------------------


def run(argv, client, env=None):
    out, err = io.StringIO(), io.StringIO()
    made = []

    def factory(api_key, base_url):
        made.append((api_key, base_url))
        return client

    status = main(argv, env={"QUBE_API_KEY": "key", **(env or {})}, out=out, err=err, client_factory=factory)
    return status, out.getvalue(), err.getvalue(), made


def test_cli_writes_the_module_and_check_passes_on_it(document, tmp_path):
    output = str(tmp_path / "app" / "qube_workflows.py")
    status, out, err, _ = run(["workflows", "--drafts", "--output", output], FakeClient(document))
    assert status == 0, err
    assert "wrote %s" % output in out and "4 workflows from %s (with drafts)" % SOURCE in out
    assert "warning: QuBe Sync's operations" in err
    with open(output, encoding="utf-8") as f:
        assert f.read() == render(document, drafts=True).python
    status, out, _, _ = run(["workflows", "--drafts", "--output", output], FakeClient(document))
    assert "identical %s" % output in out
    client = FakeClient(NOT_MODIFIED)
    status, out, err, _ = run(["workflows", "--check", "--output", output], client)
    assert (status, client.calls[0]["include_drafts"]) == (0, True), err
    assert "is up to date" in out


