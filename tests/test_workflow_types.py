def test_renames_what_would_clash(tmp_path):
    files = render(
        workflow(
            {
                "type": "object",
                "additionalProperties": False,
                "required": ["from"],
                "properties": {
                    "from": {"$operation": "customer.create"},
                    "version": {"type": "integer"},
                    "type": {"type": "string"},
                    "lambda": {"type": "boolean"},
                },
                "discriminator": {"propertyName": "kind"},
                "oneOf": [
                    {"title": "start", "properties": {"kind": {"const": "a"}}},
                    {"title": "class", "properties": {"kind": {"const": "b"}}},
                ],
            },
            key="class",
        )
    )
    python = files.python
    assert "class_ = ClassWorkflow\n" in python
    assert "    def start_(\n        connection: _Connection,\n        from_: CustomerCreateParams,\n" in python
    assert "    def class_(\n" in python and "    def class_input(\n" in python and "    def start_input(\n" in python
    assert '            "from": from_,\n            "lambda": lambda_,\n            "type": type,\n            "version": version_,\n' in python
    module = load(python, tmp_path)
    assert module.class_.WORKFLOW == "class"
    assert module.ClassWorkflow.start_input({"name": "x"}, lambda_=True, version_=2) == {
        "kind": "a",
        "from": {"name": "x"},
        "lambda": True,
        "version": 2,
    }
    assert set(module.ClassStartInput.__annotations__) == {"kind", "from", "lambda", "type", "version"}


