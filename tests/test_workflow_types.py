def test_cli_check_fails_on_a_stale_file_and_a_401_and_warns_when_down(document, tmp_path):
    output = str(tmp_path / "qube_workflows.py")
    run(["workflows", "--output", output], FakeClient(document))
    changed = dict(document, digest="sha256:" + "8" * 64)
    status, _, err, _ = run(["workflows", "--check", "--output", output], FakeClient(changed))
    assert status == 1 and "is out of date" in err
    status, _, err, _ = run(["workflows", "--check", "--output", output], FakeClient(APIError(401, errors="no")))
    assert status == 1 and "QuBe Sync answered 401" in err
    status, _, err, _ = run(["workflows", "--check", "--output", output], FakeClient(requests.ConnectionError("x")))
    assert status == 0 and "warning: couldn't reach QuBe Sync" in err
    status, _, err, _ = run(["workflows", "--output", output], FakeClient(requests.ConnectionError("x")))
    assert status == 1 and "nothing was written" in err


