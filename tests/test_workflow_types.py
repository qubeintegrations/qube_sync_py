def render(doc, **options):
    return workflow_types.render(doc, source=SOURCE, **options)


def load(source, tmp_path):
    """Imports a rendered module from a file of its own, under a name of its own."""
    path = tmp_path / ("qube_workflows_%s.py" % uuid.uuid4().hex)
    path.write_text(source, encoding="utf-8")
    spec = importlib.util.spec_from_file_location(path.stem, str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def workflow(input, key="sample"):
    return {
        "digest": "sha256:" + "c" * 64,
        "operations_digest": DIGEST,
        "workflows": {
            key: {"name": "Sample", "description": "A sample.", "version": 1, "draft": False, "input": input}
        },
    }


class FakeClient:
    """Answers workflow_types from a queue (a document, NOT_MODIFIED, or an exception to raise),
    recording the calls, and records start_run."""

    base_url = "https://qubesync.com"

    def __init__(self, *answers):
        self.answers = list(answers)
        self.calls = []
        self.runs = []

    def workflow_types(self, include_drafts=False, etag=None):
        self.calls.append({"include_drafts": include_drafts, "etag": etag})
        answer = self.answers.pop(0)
        if isinstance(answer, BaseException):
            raise answer
        return answer

    def start_run(self, connection_id, workflow, input, *, reference, webhook_url, version=None):
        self.runs.append(
            {
                "connection_id": connection_id,
                "workflow": workflow,
                "input": input,
                "reference": reference,
                "webhook_url": webhook_url,
                "version": version,
            }
        )
        return {"id": "run-1"}


class Connection:
    def __init__(self, qube_id):
        self.qube_id = qube_id


